#!/usr/bin/env node
/**
 * docs/reference/rate-card.md from the rate card in force (functions/src/services/usageMetering.ts,
 * DEFAULT_RATE_CARD_V1, built into functions/lib). Prompt 66 §2.3.
 *
 *   node scripts/generate-rate-card-doc.js [--check]
 */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "docs", "reference", "rate-card.md");
const { DEFAULT_RATE_CARD_V1: card } = require(path.join(ROOT, "functions", "lib", "services", "usageMetering.js"));

const UNITS = {
  firestoreReadPer100k: "100,000 document reads",
  firestoreWritePer100k: "100,000 document writes",
  firestoreDeletePer100k: "100,000 document deletes",
  functionsInvocationPerMillion: "1,000,000 function invocations",
  functionsComputeGbSecond: "GiB-second of function memory",
  storageGbMonth: "GiB-month stored (not applied: no stored-bytes measurement yet)",
  fcmPerThousand: "1,000 push messages",
  locationPingPer100k: "100,000 location pings (internal, not a Google SKU)",
};
const v = card.verification || {};
const verifiedCount = Object.keys(card.rates).filter((k) => v[k] && v[k].verified).length;
const free = card.freeTier;
const md = [
  "# Rate card", "",
  "Generated by `scripts/generate-rate-card-doc.js` from `DEFAULT_RATE_CARD_V1` in `functions/src/services/usageMetering.ts`. Do not edit.", "",
  `Version \`${card.version}\`, effective ${card.effectiveDate}, currency ${card.currency}. Versions are kept in \`usageRateCards\`; an answer for a past date uses the version in force on that date. Cost is never stored (D-22): quantities × these prices, when read, and every answer says which version it used and whether the prices are verified.`, "",
  `**Verified prices: ${verifiedCount} of ${Object.keys(card.rates).length}.** An unverified price is an estimate to be checked against the official pricing page (Firestore, Cloud Run functions, Cloud Storage, region asia-south1) or the Cloud Billing Catalog API before any number is shown as a cost; that check is on the production checklist.`, "",
  "| Rate | Unit | Price | Verified | Source |", "|---|---|---|---|---|",
  ...Object.entries(card.rates).map(([k, price]) => `| \`${k}\` | ${UNITS[k] || ""} | ${price} ${card.currency} | ${v[k] && v[k].verified ? `yes (${v[k].verifiedAt})` : "**no**"} | ${v[k] ? v[k].source : "—"} |`),
  "",
  "## Project free allowance", "",
  free ? `Applied to the whole project, daily, reset around midnight Pacific time; **not allocated to organizations** (shown as one separate line). Verified ${free.verifiedAt} from ${free.source}.` : "Not recorded.", "",
  ...(free ? ["| Allowance | Amount |", "|---|---|", `| document reads per day | ${free.firestoreReadsPerDay.toLocaleString("en-US")} |`, `| document writes per day | ${free.firestoreWritesPerDay.toLocaleString("en-US")} |`, `| document deletes per day | ${free.firestoreDeletesPerDay.toLocaleString("en-US")} |`, `| stored data | ${free.firestoreStoredGiB} GiB |`, `| outbound data transfer per month | ${free.egressGiBPerMonth} GiB |`, ""] : []),
].join("\n");

if (process.argv.includes("--check")) {
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== md) { console.error("[FAIL] stale: docs/reference/rate-card.md. Run: node scripts/generate-rate-card-doc.js"); process.exit(1); }
  console.log("[PASS] rate card document is up to date.");
} else {
  fs.writeFileSync(OUT, md);
  console.log(`Written docs/reference/rate-card.md (${card.version}; ${verifiedCount} verified prices)`);
}

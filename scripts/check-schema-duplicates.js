function detectModelFindings(model) {
  const findings = [];
  const add = (code, collection, field, message) => findings.push({ code, collection, field, message });
  const docs = Object.values(model.interfaces).filter((i) => i.collection);

  for (const doc of docs) {
    const units = [{ path: "", iface: doc.name, isArray: false }].concat(embeddedTypes(model, doc.name));
    for (const unit of units) {
      const fields = model.interfaces[unit.iface].fields;
      const names = new Set(fields.map((f) => f.leaf));
      const at = (leaf) => (unit.path ? `${unit.path}.${leaf}` : leaf);
      if (unit.isDoc) add("D3_EMBEDDED_ENTITY", doc.collection, unit.path, `embeds ${unit.iface} (store its id instead)`);
      for (const f of fields) {
        const full = unit.path ? `${unit.path}.${f.name}` : f.name;
        // D1 display copies
        const prefix = ENTITY_PREFIXES.find((p) => ATTR_SUFFIXES.some((s) => f.leaf === `${p}${s}`));
        if (prefix && !(prefix === doc.collection.replace(/s$/, ""))) add("D1_DISPLAY_COPY", doc.collection, full, `"${f.leaf}" copies an attribute of ${prefix}`);
        if (/^(nameSnapshot|referenceNumber|customerSnapshot)$/.test(f.leaf)) add("D1_DISPLAY_COPY", doc.collection, full, `"${f.leaf}" is a descriptive snapshot`);
        // D5 derived
        if (DERIVED.includes(f.leaf)) add("D5_DERIVED_FIELD", doc.collection, full, `"${f.leaf}" is derivable (register as R2/R3 with writer + reconcile, or compute at read)`);
        // D8 arrays
        const parts = f.type.split("|").map((x) => x.trim()).filter((x) => x && !/^(null|undefined)$/.test(x));
        if (parts.length && parts.every((x) => /\[\]$/.test(x) || /^Array</.test(x))) add("D8_UNBOUNDED_ARRAY", doc.collection, full, `array "${f.leaf}" needs a registered cap enforced by the Zod input`);
      }
      // D2 / D3 embedded objects carrying referenced attributes
      if (unit.path) {
        const idFields = fields.map((f) => f.leaf).filter((n) => entityOfId(n) && ENTITY_COLLECTION[entityOfId(n)]);
        for (const idField of idFields) {
          const target = model.collections[ENTITY_COLLECTION[entityOfId(idField)]];
          if (!target) continue;
          const targetAttrs = new Set(model.interfaces[target].fields.map((f) => f.leaf).filter((n) => DESCRIPTIVE.includes(n)));
          const shared = fields.map((f) => f.leaf).filter((n) => targetAttrs.has(n) || (n === "itemName" && targetAttrs.has("name")));
          for (const s of shared) add("D2_SHARED_ATTRIBUTE", doc.collection, at(s), `"${s}" duplicates ${target}.${s === "itemName" ? "name" : s} beside ${idField}`);
        }
        const descr = fields.map((f) => f.leaf).filter((n) => DESCRIPTIVE.includes(n));
        if (!idFields.length && descr.length >= 2 && !["address", "contact", "bankDetails"].includes(unit.path.split(".").pop())) {
          add("D3_EMBEDDED_ENTITY", doc.collection, unit.path, `embedded object with descriptive attributes ${descr.join(", ")}`);
        }
      }
      // D4 state pairs
      for (const [a, b] of STATE_PAIRS) {
        if (names.has(a) && names.has(b)) add("D4_STATE_DUPLICATION", doc.collection, at(`${a}+${b}`), `"${a}" and "${b}" express one state`);
      }
      const statusField = fields.find((f) => f.leaf === "status");
      if (statusField && names.has("approvalStatus") && /pending_approval/.test(statusField.type)) {
        add("D4_STATE_DUPLICATION", doc.collection, at("status+approvalStatus"), "status carries approval states and approvalStatus repeats them");
      }
      // D6 time
      for (const f of fields) {
        const stem = f.leaf.replace(/(At|Date|DateString|Ymd)$/, "");
        if (stem && stem !== f.leaf) {
          const twins = fields.filter((g) => g !== f && g.leaf !== f.leaf && g.leaf.replace(/(At|Date|DateString|Ymd)$/, "") === stem && /(At|Date|DateString|Ymd)$/.test(g.leaf));
          if (twins.length && f.leaf < twins[0].leaf) add("D6_DUPLICATE_TIME", doc.collection, at(`${f.leaf}+${twins[0].leaf}`), "two fields for one instant/date");
        }
        if (names.has("date") && names.has("dateString") && f.leaf === "date") add("D6_DUPLICATE_TIME", doc.collection, at("date+dateString"), "two fields for one date");
      }
    }
    // D7 self id
    const singular = doc.collection.replace(/ies$/, "y").replace(/s$/, "");
    for (const f of model.interfaces[doc.name].fields) {
      if (f.name === "id" || f.name === `${singular}Id`) add("D7_SELF_ID", doc.collection, f.name, `"${f.name}" repeats the document id`);
    }
  }
  return findings;
}

/** D9: identical z.object shapes (normalised body text) declared under two names. */
function detectZodClones(text) {
  const findings = [];
  const re = /export const (\w+)\s*=\s*z\s*\.(?:strictObject|object)\(\{/g;
  const bodies = new Map();
  let m;
  while ((m = re.exec(text))) {
    let depth = 1;
    let j = re.lastIndex;
    while (j < text.length && depth > 0) {
      if (text[j] === "{") depth++;
      else if (text[j] === "}") depth--;
      j++;
    }
    const body = text.slice(re.lastIndex, j - 1).replace(/\/\/.*$/gm, "").replace(/\s+/g, "");
    if (body.length < 40) continue;
    if (bodies.has(body)) findings.push({ code: "D9_ZOD_CLONE", collection: "(zod)", field: `${bodies.get(body)}=${m[1]}`, message: `${m[1]} repeats the shape of ${bodies.get(body)}` });
    else bodies.set(body, m[1]);
  }
  return findings;
}

// ---------------------------------------------------------------------------
// Register (allowlist) validation and doc generation
// ---------------------------------------------------------------------------

function loadAllowlist() {
  return JSON.parse(fs.readFileSync(ALLOWLIST, "utf8"));
}

const sourceText = (() => {
  let cache = null;
  return () => {
    if (cache) return cache;
    const files = [];
    const walk = (d) => {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        if (["node_modules", "lib", ".git"].includes(e.name)) continue;
        const p = path.join(d, e.name);
        if (e.isDirectory()) walk(p);
        else if (/\.(ts|js|cjs)$/.test(e.name)) files.push(fs.readFileSync(p, "utf8"));
      }
    };
    walk(path.join(ROOT, "functions/src"));
    walk(path.join(ROOT, "functions/scripts"));
    cache = files.join("\n");
    return cache;
  };
})();

function validateRegister(list, model) {
  const problems = [];
  const fieldExists = (collection, field) => {
    const iface = model.collections[collection];
    if (!iface) return false;
    const first = field.split(/[+.]/)[0];
    const doc = model.interfaces[iface];
    if (doc.fields.some((f) => f.name === first || f.name === field)) return true;
    return embeddedTypes(model, iface).some((u) => field.startsWith(`${u.path}.`) &&
      model.interfaces[u.iface].fields.some((f) => field.slice(u.path.length + 1).split(/[+.]/)[0] === f.name));
  };
  for (const e of list.entries) {
    const label = `${e.id} (${e.collection}.${e.field})`;
    if (!e.reason || e.reason.length < 15) problems.push(`${label}: missing reason`);
    if (!["R2", "R3", "R4", "OWNED", "BOUNDED_ARRAY", "STATE", "TIME"].includes(e.kind)) problems.push(`${label}: unknown kind ${e.kind}`);
    if (e.collection !== "(zod)" && !fieldExists(e.collection, e.field)) problems.push(`${label}: field no longer exists in models.ts`);
    if (e.kind === "R3") {
      if (!e.writerFunction) problems.push(`${label}: R3 cache needs writerFunction`);
      if (!e.reconcileTest) problems.push(`${label}: R3 cache needs reconcileTest`);
    }
    if (e.writerFunction && !sourceText().includes(e.writerFunction)) problems.push(`${label}: writer "${e.writerFunction}" not found in source`);
    if (e.reconcileTest && !sourceText().includes(e.reconcileTest)) problems.push(`${label}: reconcile test "${e.reconcileTest}" not found`);
    if (e.kind === "BOUNDED_ARRAY" && !(e.cap > 0)) problems.push(`${label}: bounded array needs cap`);
    if (e.cap && !e.serverWritten) {
      // The cap must be enforced by the Zod input: `<field>: z.array(…).max(N)` with N ≤ cap
      const leaf = e.field.split(".").pop();
      const schemas = fs.readFileSync(SCHEMAS, "utf8");
      const consts = { MAX_DOCUMENT_LINES: Number((schemas.match(/MAX_DOCUMENT_LINES = (\d+)/) || [])[1]) };
      const caps = [...schemas.matchAll(new RegExp(`\\b${leaf}: z\\.array\\(.*\\)\\.(?:min\\(\\d+\\)\\.)?max\\((\\w+)\\)`, "g"))]
        .map((m) => (/^\d+$/.test(m[1]) ? Number(m[1]) : consts[m[1]]));
      if (!caps.length) problems.push(`${label}: no Zod .max() found for "${leaf}"`);
      else if (caps.some((c) => !(c <= e.cap))) problems.push(`${label}: Zod cap ${caps.join("/")} exceeds registered cap ${e.cap}`);
    }
  }
  return problems;
}

function renderRegister(list) {
  const rows = list.entries
    .slice()
    .sort((a, b) => `${a.collection}.${a.field}`.localeCompare(`${b.collection}.${b.field}`))
    .map((e) => `| ${e.id} | ${e.kind} | \`${e.collection}\` | \`${e.field}\` | ${e.reason.replace(/\|/g, "/")} | ${e.writerFunction ? `\`${e.writerFunction}\`` : "—"} | ${e.reconcileTest ? e.reconcileTest : e.cap ? `cap ${e.cap}` : "—"} |`);
  return [REG_START, "",
    "| ID | Kind | Collection | Field | Reason | Single writer | Reconcile / cap |",
    "|---|---|---|---|---|---|---|", ...rows, "", REG_END].join("\n");
}

function matchesEntry(finding, entries) {
  return entries.some((e) => e.collection === finding.collection && (e.field === finding.field || (e.codes || []).includes(finding.code) && finding.field.startsWith(`${e.field}.`)));
}

// ---------------------------------------------------------------------------

function run({ write = false, report = false } = {}) {
  const model = parseModels(fs.readFileSync(MODELS, "utf8"));
  const findings = detectModelFindings(model).concat(detectZodClones(fs.readFileSync(SCHEMAS, "utf8")));
  const list = loadAllowlist();
  const unregistered = findings.filter((f) => !matchesEntry(f, list.entries));
  const problems = validateRegister(list, model);
  const stale = list.entries.filter((e) => !findings.some((f) => f.collection === e.collection && (f.field === e.field || f.field.startsWith(`${e.field}.`))));

  const doc = fs.readFileSync(DATA_MODEL_DOC, "utf8");
  const rendered = renderRegister(list);
  const s = doc.indexOf(REG_START);
  const t = doc.indexOf(REG_END);
  if (write) {
    if (s < 0 || t < 0) throw new Error("docs/data-model.md has no DUPLICATION-REGISTER markers");
    fs.writeFileSync(DATA_MODEL_DOC, doc.slice(0, s) + rendered + doc.slice(t + REG_END.length));
    console.log("✓ docs/data-model.md duplication register regenerated");
  } else if (s < 0 || doc.slice(s, t + REG_END.length) !== rendered) {
    problems.push("docs/data-model.md duplication register is out of date (run with --write)");
  }

  const byCode = {};
  for (const f of findings) byCode[f.code] = (byCode[f.code] || 0) + 1;
  console.log(`Schema duplication scan: ${Object.keys(model.collections).length} collection interfaces, ${findings.length} candidate findings (${Object.entries(byCode).map(([k, v]) => `${k} ${v}`).join(", ")}), ${list.entries.length} registered exceptions.`);
  if (report) for (const f of findings) console.log(`  ${matchesEntry(f, list.entries) ? "registered" : "OPEN      "} [${f.code}] ${f.collection}.${f.field} — ${f.message}`);
  for (const e of stale) problems.push(`register entry ${e.id} (${e.collection}.${e.field}) matches no finding (remove it)`);
  if (unregistered.length || problems.length) {
    for (const f of unregistered) console.error(`[${f.code}] ${f.collection}.${f.field} — ${f.message}`);
    for (const p of problems) console.error(`[REGISTER] ${p}`);
    console.error(`✗ ${unregistered.length} unregistered duplication finding(s), ${problems.length} register problem(s).`);
    return 1;
  }
  console.log("[PASS] Zero unregistered schema duplication; register valid and docs in sync.");
  return 0;
}

function selfTest() {
  const sample = `
/**
 * 1. widgets/{widgetId}
 */
export interface WidgetDoc {
  widgetId: string;
  customerId: string;
  customerName: string;
  isActive: boolean;
  status: string;
  lines: WidgetLine[];
  createdAt: string;
  createdDate: string;
}
export interface WidgetLine {
  productId: string;
  itemName: string;
  sku: string;
}
/**
 * 2. products/{productId}
 */
export interface ProductDoc {
  name: string;
  sku: string;
}`;
  const model = parseModels(sample);
  const codes = new Set(detectModelFindings(model).map((f) => `${f.code}:${f.field}`));
  const expected = ["D7_SELF_ID:widgetId", "D1_DISPLAY_COPY:customerName", "D4_STATE_DUPLICATION:isActive+status",
    "D8_UNBOUNDED_ARRAY:lines", "D6_DUPLICATE_TIME:createdAt+createdDate", "D2_SHARED_ATTRIBUTE:lines.itemName", "D2_SHARED_ATTRIBUTE:lines.sku"];
  const missing = expected.filter((e) => !codes.has(e));
  const clones = detectZodClones("export const A = z.object({ name: z.string().min(2), price: z.number().min(0) });\nexport const B = z.object({ name: z.string().min(2), price: z.number().min(0) });");
  if (missing.length || clones.length !== 1) {
    console.error(`Self-test FAILED. Missing: ${missing.join(", ")}; clones found: ${clones.length}; got: ${[...codes].join(", ")}`);
    return 1;
  }
  console.log(`[PASS] self-test: ${expected.length} seeded duplications + 1 Zod clone detected.`);
  return 0;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  process.exit(args.includes("--test") ? selfTest() : run({ write: args.includes("--write"), report: args.includes("--report") }));
}

module.exports = { parseModels, detectModelFindings, detectZodClones, run };

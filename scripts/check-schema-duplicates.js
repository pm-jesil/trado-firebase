#!/usr/bin/env node
/**
 * Trado zero-duplication schema checker (static, Part 2.2 / 1.4 / 4.4).
 *
 * Source of truth: functions/src/types/models.ts (collection documents and their embedded
 * types) and functions/src/validation/schemas.ts (Zod input shapes). Exceptions live ONLY in
 * functions/scripts/duplication-allowlist.json; the "Allowed duplication register" table in
 * docs/data-model.md is generated from it (`--write`) and drift-checked here.
 *
 * Detectors (each finding must be removed or registered with a reason):
 *  D1 DISPLAY_COPY        <entity>(Name|Email|Phone|Mobile|Sku|Code|Title|Label|Address|Number)
 *                         or nameSnapshot / referenceNumber: a descriptive copy of a referenced record
 *  D2 SHARED_ATTRIBUTE    an embedded object holds <x>Id plus a descriptive attribute of x
 *  D3 EMBEDDED_ENTITY     an object/array type that carries >= 2 descriptive attributes of a
 *                         referenced entity, or embeds another *Doc interface
 *  D4 STATE_DUPLICATION   two fields expressing one state (isActive+status, isPaid+paymentStatus, ...)
 *  D5 DERIVED_FIELD       derivable in the same document (lineTotal, balanceAmount, totals, ...)
 *  D6 DUPLICATE_TIME      createdAt + createdDate, date + dateString, ...
 *  D7 SELF_ID             a field that repeats the document id
 *  D8 UNBOUNDED_ARRAY     array field without a registered cap that the Zod input enforces
 *  D9 ZOD_CLONE           structurally identical z.object shapes declared twice
 *  R  REGISTER            register entry invalid: no reason, field gone, writer/reconcile missing
 *
 * Usage: node scripts/check-schema-duplicates.js [--write] [--report] [--test]
 */
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const MODELS = path.join(ROOT, "functions/src/types/models.ts");
const SCHEMAS = path.join(ROOT, "functions/src/validation/schemas.ts");
const ALLOWLIST = path.join(ROOT, "functions/scripts/duplication-allowlist.json");
const DATA_MODEL_DOC = path.join(ROOT, "docs/data-model.md");
const REG_START = "<!-- DUPLICATION-REGISTER:START (generated by scripts/check-schema-duplicates.js --write; do not edit) -->";
const REG_END = "<!-- DUPLICATION-REGISTER:END -->";

const DESCRIPTIVE = ["name", "displayName", "email", "phone", "mobile", "address", "billingAddress", "shippingAddress",
  "sku", "barcode", "title", "label", "code", "taxNumber", "contactPerson", "brand"];
const ENTITY_PREFIXES = ["customer", "vendor", "product", "party", "rider", "createdBy", "updatedBy", "unit", "item",
  "category", "branch", "employee", "user", "team", "role", "payee", "salesperson", "assignee", "assignedTo",
  "organization", "department", "jobRole", "plan", "reference", "bill", "outflow", "payment", "delivery", "return"];
const ATTR_SUFFIXES = ["Name", "Email", "Phone", "Mobile", "Sku", "Code", "Title", "Label", "Address", "Number"];
const STATE_PAIRS = [["isActive", "status"], ["isPaid", "paymentStatus"], ["isApproved", "approvalStatus"],
  ["isDelivered", "status"], ["deletedAt", "status"], ["isDeleted", "status"], ["isVoided", "status"]];
const DERIVED = ["lineTotal", "subtotal", "subTotal", "grossAmount", "balanceAmount", "totalAmount", "discountTotal",
  "taxTotal", "paymentStatus", "baseQuantity", "balanceAfter", "totalRefundAmount", "memberCount", "branchCount",
  "activeEmployeeCount", "currentStock", "allocatedStock", "outstandingBalance", "outstandingPayable", "totalSpend",
  "totalPurchase", "returnedQty", "paidAmount", "productIds", "assignedBranchIds", "weightedAverageCost", "changedFields"];

// ---------------------------------------------------------------------------
// models.ts parser
// ---------------------------------------------------------------------------

function collectionFor(name, comment) {
  const m = comment.match(/\*\s*\d+[a-z]?\.\s+([A-Za-z/{}_]+)/);
  if (m) {
    const parts = m[1].split("/").filter((p) => !p.startsWith("{"));
    return parts[parts.length - 1];
  }
  if (!name.endsWith("Doc")) return null;
  const base = name.slice(0, -3);
  const lower = base[0].toLowerCase() + base.slice(1);
  if (/(Daily|Monthly)$/.test(lower)) return lower;
  if (lower === "branch") return "branches";
  return lower.endsWith("y") ? `${lower.slice(0, -1)}ies` : `${lower}s`;
}

/** Returns { interfaces: {Name: {collection, line, fields:[{name,type,line,optional}]}}, collections: {coll: Name} } */
function parseModels(text) {
  const lines = text.split("\n");
  const interfaces = {};
  let comment = "";
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\/\*\*/.test(line)) comment = "";
    if (/^\s*\*/.test(line) || /^\/\*\*/.test(line)) comment += `${line}\n`;
    const m = line.match(/^export interface (\w+)/);
    if (!m) continue;
    const name = m[1];
    const fields = [];
    let depth = (line.match(/{/g) || []).length - (line.match(/}/g) || []).length;
    const stack = [];
    for (i = i + 1; i < lines.length && depth > 0; i++) {
      const l = lines[i].replace(/\/\/.*$/, "").replace(/\/\*.*?\*\//g, "");
      const f = l.match(/^\s*(\w+)(\?)?:\s*(.*)$/);
      if (f && depth >= 1) {
        const prefix = stack.map((s) => s.name).join(".");
        const full = prefix ? `${prefix}.${f[1]}` : f[1];
        const type = f[3].replace(/;\s*$/, "").trim();
        fields.push({ name: full, leaf: f[1], type, optional: !!f[2], line: i + 1 });
        if (type.startsWith("{") && !type.includes("}")) stack.push({ name: f[1], depth: depth + 1 });
      }
      depth += (l.match(/{/g) || []).length - (l.match(/}/g) || []).length;
      while (stack.length && depth < stack[stack.length - 1].depth) stack.pop();
    }
    i--;
    interfaces[name] = { name, collection: collectionFor(name, comment), fields };
    comment = "";
  }
  const collections = {};
  for (const it of Object.values(interfaces)) if (it.collection) collections[it.collection] = it.name;
  return { interfaces, collections };
}

/** Embedded types reachable from a collection document: [{ path, iface }] */
function embeddedTypes(model, rootName) {
  const out = [];
  const seen = new Set([rootName]);
  const walk = (ifaceName, prefix) => {
    for (const f of model.interfaces[ifaceName].fields) {
      const t = f.type.replace(/\[\]|\| null|\| undefined|Partial<|Record<string,\s*|>/g, "").trim();
      if (model.interfaces[t] && !seen.has(t)) {
        seen.add(t);
        out.push({ path: `${prefix}${f.name}`, iface: t, isArray: /\[\]/.test(f.type), isDoc: t.endsWith("Doc") });
        if (!t.endsWith("Doc")) walk(t, `${prefix}${f.name}.`);
      }
    }
  };
  walk(rootName, "");
  return out;
}

const entityOfId = (field) => {
  const m = field.match(/^(\w+?)(MembershipId|Id)$/);
  if (!m) return null;
  return m[1];
};
const ENTITY_COLLECTION = {
  customer: "customers", vendor: "vendors", product: "products", category: "categories", unit: "units",
  branch: "branches", team: "teams", role: "roles", department: "departments", user: "users", bill: "bills",
  outflow: "outflows", organization: "organizations", plan: "subscriptionPlans", rider: "memberships",
  payee: "memberships", salesperson: "memberships", assignedTo: "memberships", leader: "memberships",
};


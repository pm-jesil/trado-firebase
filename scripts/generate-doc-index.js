#!/usr/bin/env node
/**
 * Trado Documentation Indexer & Human Map Generator
 * 
 * Scans all documentation files (*.md, configs, generated artifacts) in the repository,
 * categorizes them by lifecycle classification (KEEP+UPDATE, REWRITE, MERGE, ARCHIVE, GENERATED),
 * generates `docs/generated/doc-index.json`, and writes `docs/README.md`.
 */

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const DOCS_DIR = path.join(ROOT, "docs");
const JSON_OUT = path.join(DOCS_DIR, "generated/doc-index.json");
const MAP_OUT = path.join(DOCS_DIR, "README.md");

function walkDir(dir, filter) {
  let results = [];
  const list = fs.readdirSync(dir);
  for (const file of list) {
    if (file === "node_modules" || file === ".git" || file === "lib" || file === ".local") continue; // .local: runtime output, rewritten while units run
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat && stat.isDirectory()) {
      results = results.concat(walkDir(fullPath, filter));
    } else if (filter(fullPath)) {
      results.push(fullPath);
    }
  }
  return results;
}

const candidateFiles = [
  path.join(ROOT, "README.md"),
  path.join(ROOT, "functions/README.md"),
  ...walkDir(DOCS_DIR, (f) => f.endsWith(".md")),
];

// Keep only existing unique files
const uniqueFiles = Array.from(new Set(candidateFiles)).filter((f) => fs.existsSync(f));

function classifyDoc(relPath) {
  if (relPath.includes("generated/") || relPath.endsWith("callable-and-trigger-inventory.md")) {
    return "GENERATED";
  }
  if (relPath.startsWith("docs/audit/")) {
    if (relPath.includes("issue-ledger") || relPath.includes("test-coverage-matrix")) {
      return "KEEP+UPDATE";
    }
    return "ARCHIVE";
  }
  if (relPath.startsWith("docs/features/") || relPath.startsWith("docs/workflows/")) {
    return "KEEP+UPDATE";
  }
  if (relPath === "docs/data-model.md" || relPath === "docs/api-reference.md" ||
      relPath === "README.md" || relPath === "functions/README.md" ||
      relPath === "docs/testing-guide.md" || relPath === "docs/permissions-and-roles.md") {
    return "KEEP+UPDATE";
  }
  if (relPath === "docs/production-readiness.md" || relPath === "docs/current-regression-report.md") {
    return "REWRITE";
  }
  return "KEEP+UPDATE";
}

const docEntries = uniqueFiles.map((fullPath) => {
  const relPath = path.relative(ROOT, fullPath).replace(/\\/g, "/");
  const content = fs.readFileSync(fullPath, "utf8");
  // A generator marks its output "Do not edit." near the top: that document is GENERATED whatever its folder.
  const generated = /Do not edit/i.test(content.split("\n").slice(0, 8).join("\n"));
  const classification = generated ? "GENERATED" : classifyDoc(relPath);
  const firstHeaderMatch = content.match(/^#\s+(.+)$/m);
  const title = firstHeaderMatch ? firstHeaderMatch[1].trim() : path.basename(relPath);

  // No line count for a GENERATED document: its generator rewrites it in the same verification run (some
  // are run outputs the impact system ignores), so the index would go stale with nothing to rerun it.
  return {
    path: relPath,
    title,
    classification,
    lineCount: generated ? null : content.split("\n").length,
  };
});

// No timestamps or mtimes: the index is a pure function of the docs, so --check can compare it exactly.
const CHECK = process.argv.includes("--check");
const jsonText = JSON.stringify({
  version: "1.0.0",
  totalDocuments: docEntries.length,
  countsByClassification: {
    "KEEP+UPDATE": docEntries.filter((d) => d.classification === "KEEP+UPDATE").length,
    "REWRITE": docEntries.filter((d) => d.classification === "REWRITE").length,
    "ARCHIVE": docEntries.filter((d) => d.classification === "ARCHIVE").length,
    "GENERATED": docEntries.filter((d) => d.classification === "GENERATED").length,
  },
  documents: docEntries,
}, null, 2);

// Generate docs/README.md human map
let md = `# Trado Repository Documentation Map\n\nGenerated by \`scripts/generate-doc-index.js\`. Do not edit.\n\n`;
md += `> **Automated Truth Guarantee**: This index is mechanically generated and verified by \`scripts/check-doc-index.js\` as part of \`npm run test:static\`.\n\n`;
md += `## Documentation Summary\n\n`;
md += `| Classification | Count | Description |\n`;
md += `| --- | --- | --- |\n`;
md += `| **KEEP+UPDATE** | ${docEntries.filter((d) => d.classification === "KEEP+UPDATE").length} | Canonical architectural guides, API contracts, entity schemas, and core workflows. |\n`;
md += `| **REWRITE** | ${docEntries.filter((d) => d.classification === "REWRITE").length} | Status reports and readiness assessments updated with verified test evidence. |\n`;
md += `| **ARCHIVE** | ${docEntries.filter((d) => d.classification === "ARCHIVE").length} | Historical audit snapshots and refactoring reports preserved for provenance. |\n`;
md += `| **GENERATED** | ${docEntries.filter((d) => d.classification === "GENERATED").length} | Mechanically compiled catalogs, OpenAPI specs, policy vectors, and inventories. |\n`;
md += `| **Total** | **${docEntries.length}** | Total indexed documentation assets |\n\n`;

md += `## Document Directory\n\n`;
md += `| Document | Classification | Title | Lines |\n`;
md += `| --- | --- | --- | --- |\n`;

for (const doc of docEntries.sort((a, b) => a.path.localeCompare(b.path))) {
  md += `| [\`${doc.path}\`](../${doc.path}) | \`${doc.classification}\` | ${doc.title.replace(/\|/g, "-")} | ${doc.lineCount === null ? "generated" : doc.lineCount} |\n`;
}

md += `\n---\n*Generated by \`scripts/generate-doc-index.js\`*\n`;

if (CHECK) {
  // Used by test:static: the committed index and map must be what this generator produces now.
  const stale = [[JSON_OUT, jsonText], [MAP_OUT, md]].filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text);
  if (stale.length) {
    console.error(`[FAIL] stale: ${stale.map(([file]) => path.relative(ROOT, file)).join(", ")}. Run: node scripts/generate-doc-index.js`);
    process.exit(1);
  }
  console.log(`[PASS] documentation index and map are up to date (${docEntries.length} documents).`);
} else {
  fs.mkdirSync(path.dirname(JSON_OUT), { recursive: true });
  fs.writeFileSync(JSON_OUT, jsonText);
  fs.writeFileSync(MAP_OUT, md);
  console.log(`✓ Generated documentation index (${docEntries.length} documents) and map: ${path.relative(ROOT, JSON_OUT)}, ${path.relative(ROOT, MAP_OUT)}`);
}

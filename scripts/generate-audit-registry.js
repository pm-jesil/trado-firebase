#!/usr/bin/env node
/**
 * Audit action registry (prompt 66 §6.2): one entry per callable and trigger, derived from source.
 *
 *   node scripts/generate-audit-registry.js [--check]
 *
 * Writes functions/src/constants/auditRegistry.ts (read by services/auditRecorder.ts) and
 * docs/reference/audit-actions.md. --check fails when either is stale, so a new export cannot ship
 * without an action (guard, D-23).
 *
 *   action        "<entity>.<verb>" from the export name (customersCreate → customer.create)
 *   category      mutation | read_sensitive | export | auth | file | admin | system | none (plain reads)
 *   collection    the business collection the export primarily writes (its entity), or null
 *   inputFields   top-level request fields that carry the reason for the action (copied into the event)
 */
const fs = require("node:fs");
const path = require("node:path");
const truth = require("./lib/source-truth.js");

const ROOT = truth.ROOT;
const TS_OUT = path.join(ROOT, "functions", "src", "constants", "auditRegistry.ts");
const MD_OUT = path.join(ROOT, "docs", "reference", "audit-actions.md");

const singular = (w) => (w.endsWith("ies") ? `${w.slice(0, -3)}y` : /(ss|x|ch|sh)es$/.test(w) ? w.slice(0, -2) : w.endsWith("s") && !w.endsWith("ss") ? w.slice(0, -1) : w);
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

/** Entities stored under another collection name. */
const COLLECTION_OF = { employee: "memberships", plan: "subscriptionPlans", platform: "users" };
const COLLECTIONS = truth.getCollections().collections.map((c) => c.key.split("/").pop());
/** Request fields kept on the event besides reasons, because a reader queries them (plan-delete check: details.planId). */
const EXTRA_INPUT_FIELDS = { organizationsSetSubscription: ["planId", "action"], organizationsCreate: ["planId"] };
const TRIGGER_ACTIONS = { onStorageObjectFinalized: "storage_object.finalize", subscriptionAndUsageSweep: "subscription.sweep" };

function actionOf(name) {
  const trigger = name.match(/^on([A-Z][a-z]+)Written$/);
  if (trigger) return { entity: trigger[1].toLowerCase(), action: `${trigger[1].toLowerCase()}.derived_update` };
  if (TRIGGER_ACTIONS[name]) return { entity: TRIGGER_ACTIONS[name].split(".")[0], action: TRIGGER_ACTIONS[name] };
  // The entity is the longest prefix of the name that is a collection (jobRolesCreate → jobRoles),
  // else the first word (employeesCreate → employees); both in snake_case singular.
  const prefix = COLLECTIONS.filter((c) => name.startsWith(c) && /^[A-Z]/.test(name.slice(c.length))).sort((a, b) => b.length - a.length)[0] || name.match(/^[a-z]+/)[0];
  const entity = snake(singular(prefix));
  const verb = snake(name.slice(prefix.length) || "call");
  return { entity, action: `${entity}.${verb}` };
}

function categoryOf(exp, handlerText) {
  if (exp.type === "trigger") return "system";
  if (/Export|Statement/.test(exp.name)) return "export";
  if (/^auth/.test(exp.name)) return "auth";
  if (/^images/.test(exp.name)) return "file";
  if (exp.superAdminOnly) return "admin";
  if (exp.kind === "read" || exp.kind === "list") return /_SENSITIVE\b/.test(handlerText) ? "read_sensitive" : "none";
  return "mutation";
}

function handlerText(exp) {
  const src = fs.readFileSync(path.join(ROOT, exp.file), "utf8");
  const start = src.indexOf(`export const ${exp.name} =`);
  const next = src.indexOf("\nexport const ", start + 10);
  return src.slice(start, next < 0 ? undefined : next);
}

const schemas = truth.getRequestSchemas();
const entries = {};
for (const exp of truth.getExports()) {
  const { entity, action } = actionOf(exp.name);
  const text = handlerText(exp);
  const collection = COLLECTION_OF[entity] || exp.collections.find((c) => snake(singular(c.split("/").pop())) === entity) || null;
  const inputFields = [...new Set([...(EXTRA_INPUT_FIELDS[exp.name] || []), ...exp.schemas.flatMap((n) => (schemas[n] ? schemas[n].leaves.map((l) => l.path) : [])).filter((p) => !p.includes(".") && !p.includes("[") && /reason|note|decision|comment/i.test(p))])].sort();
  entries[exp.name] = {
    action,
    category: categoryOf(exp, text),
    collection,
    inputFields,
  };
}

const ts = [
  "/**",
  " * Audit action registry, generated by scripts/generate-audit-registry.js from the export registry and",
  " * the request schemas. Do not edit: regenerate (`node scripts/generate-audit-registry.js`).",
  " */",
  "",
  "export type AuditCategory = \"mutation\" | \"read_sensitive\" | \"export\" | \"auth\" | \"file\" | \"security\" | \"admin\" | \"system\" | \"none\";",
  "",
  "export interface AuditRegistryEntry {",
  "  action: string;",
  "  category: AuditCategory;",
  "  /** The business collection the export primarily writes (its entity): the event's primary target. */",
  "  collection: string | null;",
  "  /** Request fields that carry the reason for the action; copied into the event as `details`. */",
  "  inputFields: string[];",
  "}",
  "",
  "export const AUDIT_REGISTRY: Record<string, AuditRegistryEntry> = {",
  ...Object.entries(entries).map(([name, e]) => `  ${name}: { action: ${JSON.stringify(e.action)}, category: ${JSON.stringify(e.category)}, collection: ${JSON.stringify(e.collection)}, inputFields: ${JSON.stringify(e.inputFields)} },`),
  "};",
  "",
].join("\n");

const byCategory = Object.entries(entries).reduce((acc, [n, e]) => ((acc[e.category] = acc[e.category] || []).push([n, e]), acc), {});
const md = [
  "# Audit actions", "",
  "Generated by `scripts/generate-audit-registry.js` from the export registry and the request schemas. Do not edit.", "",
  "Every callable and trigger has exactly one action. Events are written by the counting layer in the same commit as the mutation (`services/auditRecorder.ts`); denied, failed, export, auth and sensitive-read events are written at the end of the request. Category `none` (plain reads) is not audited. See [the audit guide](../guides/audit-trail.md).", "",
  "| Category | Exports |", "|---|---|",
  ...Object.entries(byCategory).sort().map(([c, list]) => `| \`${c}\` | ${list.length} |`), "",
  "| Export | Action | Category | Primary collection | Reason fields |", "|---|---|---|---|---|",
  ...Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)).map(([n, e]) => `| \`${n}\` | \`${e.action}\` | ${e.category} | ${e.collection ? `\`${e.collection}\`` : "—"} | ${e.inputFields.map((f) => `\`${f}\``).join(", ") || "—"} |`),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const stale = [[TS_OUT, ts], [MD_OUT, md]].filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== t);
  if (stale.length) { console.error(`[FAIL] stale: ${stale.map(([f]) => truth.rel(f)).join(", ")}. Run: node scripts/generate-audit-registry.js`); process.exit(1); }
  console.log(`[PASS] audit registry is up to date (${Object.keys(entries).length} exports).`);
} else {
  fs.writeFileSync(TS_OUT, ts);
  fs.writeFileSync(MD_OUT, md);
  console.log(`Written ${truth.rel(TS_OUT)} and ${truth.rel(MD_OUT)}: ${Object.keys(entries).length} exports; ${Object.entries(byCategory).map(([c, l]) => `${c} ${l.length}`).join(", ")}`);
}
